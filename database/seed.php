/** Копирует стартовые файлы в public/uploads. */
function seed_media(): int
{
    $from = __DIR__ . '/seed-media';
    $to   = PUBLIC_PATH . '/uploads';
    $n = 0;

    foreach (glob($from . '/*', GLOB_ONLYDIR) as $dir) {
        $section = basename($dir);
        @mkdir($to . '/' . $section, 0775, true);
        foreach (glob($dir . '/*.*') as $file) {
            $dest = $to . '/' . $section . '/' . basename($file);
            if (!is_file($dest)) {
                copy($file, $dest);
                $n++;
            }
        }
    }

    return $n;
}

/** Есть ли уже такая строка. */
function seed_exists(PDO $pdo, string $table, string $column, string $value): bool
{
    $st = $pdo->prepare("SELECT COUNT(*) FROM `$table` WHERE `$column` = ?");
    $st->execute([$value]);
    return (int) $st->fetchColumn() > 0;
}

