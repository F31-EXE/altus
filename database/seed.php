    $body = str_replace('{BASE}', rtrim((string) config('app.base_url'), '/'), $body);
    $st = $pdo->prepare(
        'INSERT INTO posts (title, slug, excerpt, preview_image_path, body, is_published, created_at)
         VALUES (?,?,?,?,?,1,?)'
    );
    $st->execute([$title, $slug, $excerpt, $preview, $body, $date . ' 10:00:00']);
    $added['записей блога']++;
}

foreach ($added as $what => $n) {
    echo "Добавлено $what: $n\n";
}
